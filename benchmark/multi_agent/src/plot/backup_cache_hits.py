def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot cache token metrics by task from CSV data."
    )
    parser.add_argument(
        "--cache-csv",
        type=Path,
        required=True,
        help="Path to cache_hits.csv generated by collaboration.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Path to the output figure.",
    )
    parser.add_argument(
        "--failover-metrics",
        type=Path,
        default=None,
        help="Path to internal_failover_metrics.json (for fault window highlighting).",
    )
    return parser.parse_args()


def topic_sort_key(job_id: str) -> tuple[int, str]:
    if job_id.isdigit():
        return (0, f"{int(job_id):010d}")
    return (1, job_id)


def parse_timestamp(value: str | None) -> datetime | None:
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None


def extract_fault_context(
    metrics: dict,
) -> tuple[datetime | None, datetime | None, dict[str, datetime]]:
    first_fault_ts = None
    recover_ts = None
    job_completed_ts: dict[str, datetime] = {}
    for event in metrics.get("benchmark_events", []):
        event_type = str(event.get("event", ""))
        ts = parse_timestamp(event.get("timestamp"))
        if ts is None:
            continue
        if event_type == "fault_injected":
            if first_fault_ts is None or ts < first_fault_ts:
                first_fault_ts = ts
        elif event_type == "gpu_recovered":
            if first_fault_ts is not None and ts >= first_fault_ts:
                if recover_ts is None or ts < recover_ts:
                    recover_ts = ts
        elif event_type == "job_completed":
            job_id = str(event.get("job_id") or "")
            if not job_id:
                continue
            prev = job_completed_ts.get(job_id)
            if prev is None or ts < prev:
                job_completed_ts[job_id] = ts
    return first_fault_ts, recover_ts, job_completed_ts


AGENT_ROLE_TO_TASK = {
    "Planning Coordinator": "Phase 1 / Planning",
    "Data Collector": "Phase 2 / Data Collection",
    "Deep Analyst": "Phase 2 / Deep Analysis (critical)",
    "Trend Scout": "Phase 2 / Trend Scan",
    "Risk Assessor": "Phase 2 / Risk Assessment",
    "Report Synthesizer": "Phase 3 / Synthesis",
}


FALLBACK_TASK_LABEL = "All Tasks (aggregated)"


def build_task_matrix(
    csv_path: Path,
    impacted_job_ids: set[str] | None = None,
) -> tuple[list[str], dict[str, dict[str, list[int]]], dict[str, list[bool]]]:
    """Build per-task metric matrices from cache CSV.

    Returns:
        job_ids: sorted list of job IDs
        per_task_metrics: {task_label: {metric_key: [values_per_job]}}
        per_task_retried: {task_label: [bool_per_job]} whether any request was retried
    """
    job_set: set[str] = set()
    rows: list[dict] = []

    with open(csv_path, newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            job_id = row.get("job_id", "").strip()
            if not job_id:
                continue
            if impacted_job_ids is not None and job_id not in impacted_job_ids:
                continue
            task_label = row.get("task_label", "").strip()
            if not task_label:
                agent_role = row.get("agent_role", "").strip()
                task_label = AGENT_ROLE_TO_TASK.get(agent_role, "")
                row = dict(row, task_label=task_label)
            job_set.add(job_id)
            rows.append(row)

    has_task_labels = any(
        r.get("task_label", "").strip() in TASK_LABEL_ORDER for r in rows
    )

    if has_task_labels:
        task_order = TASK_LABEL_ORDER
    else:
        task_order = [FALLBACK_TASK_LABEL]

    job_ids = sorted(job_set, key=topic_sort_key)
    index = {job_id: idx for idx, job_id in enumerate(job_ids)}
    n = len(job_ids)

    per_task_metrics = {
        task: {k: [0] * n for k in METRIC_KEYS} for task in task_order
    }
    per_task_retried = {task: [False] * n for task in task_order}

    for row in rows:
        job_id = row.get("job_id", "").strip()
        task_label = row.get("task_label", "").strip()
        if not has_task_labels:
            task_label = FALLBACK_TASK_LABEL
        if job_id not in index or task_label not in per_task_metrics:
            continue
        idx = index[job_id]
        for key in METRIC_KEYS:
            per_task_metrics[task_label][key][idx] += int(row.get(key, 0) or 0)
        if row.get("is_failover_retried", "").strip().lower() in ("true", "1"):
            per_task_retried[task_label][idx] = True

    return job_ids, per_task_metrics, per_task_retried


def plot_chart(
    job_ids: list[str],
    per_task_metrics: dict[str, dict[str, list[int]]],
    per_task_retried: dict[str, list[bool]],
    fault_ts: datetime | None,
    recover_ts: datetime | None,
    job_completed_ts: dict[str, datetime],
    output_path: Path,
) -> None:
    task_labels = list(per_task_metrics.keys())
    n_tasks = len(task_labels) or 1

    plt.style.use("seaborn-v0_8-whitegrid")
    fig, axes = plt.subplots(
        n_tasks,
        1,
        figsize=(14, max(6, 2.5 * n_tasks)),
        sharex=True,
        gridspec_kw={"hspace": 0.25},
        constrained_layout=True,
    )
    if n_tasks == 1:
        axes = [axes]

    if not job_ids:
        axes[0].text(
            0.5, 0.5, EMPTY_TEXT,
            ha="center", va="center", transform=axes[0].transAxes,
            fontsize=12, color="gray",
        )
        for axis in axes[1:]:
            axis.set_axis_off()
    else:
        x = list(range(len(job_ids)))
        tick_step = max(1, len(job_ids) // 15)
        tick_positions = x[::tick_step]
        tick_labels = job_ids[::tick_step]

        fault_window_mask = []
        for job_id in job_ids:
            completed_ts = job_completed_ts.get(job_id)
            in_window = (
                fault_ts is not None
                and completed_ts is not None
                and completed_ts >= fault_ts
                and (recover_ts is None or completed_ts <= recover_ts)
            )
            fault_window_mask.append(in_window)

        for idx, task_label in enumerate(task_labels):
            axis = axes[idx]
            metrics = per_task_metrics[task_label]
            has_data = any(any(metrics[k]) for k in METRIC_KEYS)

            if not has_data:
                axis.text(
                    0.5, 0.5, "No token activity",
                    ha="center", va="center", transform=axis.transAxes,
                    fontsize=9, color="gray",
                )
            else:
                for key in METRIC_KEYS:
                    values = metrics[key]
                    if not any(values):
                        continue
                    axis.plot(
                        x, values,
                        color=METRIC_COLORS[key],
                        marker=METRIC_MARKERS[key],
                        linewidth=1.1,
                        markersize=3,
                        label=METRIC_LABELS[key],
                    )

            # Highlight failover-retried jobs
            retried = per_task_retried[task_label]
            for i, was_retried in enumerate(retried):
                if was_retried:
                    axis.axvspan(i - 0.35, i + 0.35, color="#e45756", alpha=0.10)

            # Highlight fault window
            for i, in_window in enumerate(fault_window_mask):
                if in_window and not retried[i]:
                    axis.axvspan(i - 0.35, i + 0.35, color="#f0c040", alpha=0.08)

            axis.set_ylabel(CHART_YLABEL)
            axis.set_title(TASK_LABEL_DISPLAY.get(task_label, task_label), fontsize=10, loc="left")
            axis.yaxis.set_major_formatter(ticker.StrMethodFormatter("{x:.0f}"))
            axis.grid(True, axis="y", linestyle="--", alpha=0.45)
            handles, labels = axis.get_legend_handles_labels()
            if handles:
                axis.legend(loc="upper right", frameon=True, fontsize=7, ncol=2)

        axes[-1].set_xlabel("Job ID")
        axes[-1].set_xticks(tick_positions)
        axes[-1].set_xticklabels(tick_labels, rotation=45, ha="right")
        axes[0].set_title(CHART_TITLE, fontsize=12, loc="center")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=220)
    plt.close(fig)


def main() -> None:
    args = parse_args()

    fault_ts, recover_ts, job_completed_ts = None, None, {}
    impacted_job_ids = None

    if args.failover_metrics and args.failover_metrics.is_file():
        metrics = json.loads(args.failover_metrics.read_text(encoding="utf-8"))
        fault_ts, recover_ts, job_completed_ts = extract_fault_context(metrics)
        raw_ids = metrics.get("impacted_job_ids", [])
        if raw_ids:
            impacted_job_ids = {str(j) for j in raw_ids if str(j)}

    job_ids, per_task_metrics, per_task_retried = build_task_matrix(
        args.cache_csv, impacted_job_ids
    )
    plot_chart(
        job_ids,
        per_task_metrics,
        per_task_retried,
        fault_ts,
        recover_ts,
        job_completed_ts,
        args.output,
    )


if __name__ == "__main__":
    main()
